-- Stopping an attack: a swing already sent is cancelled with the server, a swing still charging
-- is dropped before it goes, and each one's promise fails as stopped.
on("session.login", function()
	task.spawn(function()
		await(combat.set_mode("combat"))
		local sent = combat.attack(0x80000050, { power = 0 })
		task.sleep(300)
		print("sent then stopped", pawait(combat.stop()))
		print("sent", pawait(sent))
		task.sleep(1500)
		local charging = combat.attack(0x80000050, { power = 1 })
		task.sleep(100)
		combat.stop()
		print("charging", pawait(charging))
		local queued = combat.attack(0x80000050)
		combat.stop()
		print("queued", pawait(queued))
	end)
end)
