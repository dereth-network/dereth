//! `Source/ACE.Database/Models/World`: the world-database rows, one module per ACE model file.
//!
//! These are the EF entity classes as plain structs. Child collections (`ICollection<T>`) are `Vec`s
//! in primary-key order, which is the order the dump lists the rows and the order EF's
//! `context.X.Load()` fixes them up in. Navigation properties that point back to a parent row
//! (`Object`, `Parent`, `Emote`, `Recipe` on the child tables) are not carried: nothing in ACE
//! reads them, and they would make the rows cyclic. `CookBook.Recipe` (forward) is carried.
//! Nullable text columns are `Option<String>`; `NOT NULL` ones are `String`.

