//! Port of `Source/ACE.Server/WorldObjects/WorldObject_Decay.cs`: objects on a landblock rotting
//! away (dropped items, corpses, projectiles), and `DeleteObject`.
//!
//! Members are free functions over `(w, this)`. The landblock heartbeat (`Landblock.Tick`) calls
//! [`is_decayable`] and [`decay`] for each of its objects every 5 seconds.

