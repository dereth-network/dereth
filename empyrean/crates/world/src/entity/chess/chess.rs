/// `Chess.RookFlags[color]`: the rook corners and the castle each one enables.
#[must_use]
pub fn rook_flags(color: ChessColor) -> [RookCastleFlag; 2] {
    match color {
        ChessColor::White => [
            RookCastleFlag::new((0, 0), ChessMoveFlag::QueenSideCastle),
            RookCastleFlag::new((7, 0), ChessMoveFlag::KingSideCastle),
        ],
        ChessColor::Black => [
            RookCastleFlag::new((0, 7), ChessMoveFlag::QueenSideCastle),
            RookCastleFlag::new((7, 7), ChessMoveFlag::KingSideCastle),
        ],
        _ => panic!("ACE: Chess.RookFlags[{color:?}] (KeyNotFoundException)"),
    }
}

