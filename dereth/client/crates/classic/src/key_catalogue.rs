/// The catalogue the Keyboard Configuration page and the key maps use.
#[must_use]
pub fn classic() -> Catalogue {
    Catalogue {
        categories: CATEGORIES.iter().map(|c| (*c).to_owned()).collect(),
        actions: COMMANDS
            .iter()
            .map(|&(id, name, flags, category, label)| Command {
                id,
                name: name.to_owned(),
                flags,
                category,
                label: label.to_owned(),
            })
            .collect(),
        fixed: FIXED
            .iter()
            .map(|&(label, key)| FixedCommand {
                label: label.to_owned(),
                key: key.to_owned(),
            })
            .collect(),
    }
}

#[cfg(test)]
mod tests {
    //! Behaviour: none (the command table's own consistency).
    use super::*;

    #[test]
    fn every_command_is_listed_once_under_a_known_category() {
        let mut ids: Vec<u32> = COMMANDS.iter().map(|c| c.0).collect();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), COMMANDS.len());
        assert!(COMMANDS.iter().all(|c| c.3 < CATEGORIES.len()));
        assert!(COMMANDS.iter().all(|c| c.2 & 0x0100_0000 != 0));
    }
}
