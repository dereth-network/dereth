//! The advances the Windows font system gives the classic interface's own font requests.
//!
//! Windows hints each face's advance widths with the face's own instructions, which the carried
//! fonts do not share: at the small sizes the interface asks for, one advance in seven comes out a
//! pixel or more wider or narrower than the design width scaled and rounded. For the requests in
//! [`MEASURED`], each character's advance is the design width scaled and rounded plus its
//! difference here, measured with the faces Windows 11 ships; any other request takes the scaled
//! width alone.

use dereth_classic_dat::fonts::FontSpec;

/// The differences for a request, if it is one of the interface's own.
pub(crate) fn measured(spec: &FontSpec) -> Option<&'static str> {
    MEASURED
        .iter()
        .find(|(h, w, weight, face, _)| {
            *h == spec.height
                && *w == spec.width
                && *weight == spec.weight
                && *face == spec.face
                && !spec.italic
        })
        .map(|row| row.4)
}

/// The difference for the `slot`th drawn character (the Western code page's printable characters
/// in order, without the undefined bytes): `.` none, `+` and `-` one pixel either way, a digit
/// that many pixels wider, and a letter from `b` to `i` two to nine pixels narrower.
pub(crate) fn delta(deltas: &str, slot: usize) -> i32 {
    match deltas.as_bytes().get(slot).copied() {
        Some(b'+') => 1,
        Some(b'-') => -1,
        Some(d @ b'2'..=b'9') => i32::from(d - b'0'),
        Some(l @ b'b'..=b'i') => -i32::from(l - b'a' + 1),
        _ => 0,
    }
}

