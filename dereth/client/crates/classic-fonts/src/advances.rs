#[cfg(test)]
mod tests {
    //! Behaviour: none (the carried fonts' advances; the Windows comparison is in tests/cpu).
    use super::*;

    #[test]
    fn a_difference_reads_as_pixels_either_way() {
        let deltas = ".+-29bi";
        let read: Vec<i32> = (0..8).map(|slot| delta(deltas, slot)).collect();
        assert_eq!(read, [0, 1, -1, 2, 9, -2, -9, 0]);
    }

    #[test]
    fn every_request_of_the_interface_has_a_difference_for_each_printable_character() {
        for (_, height, width, weight, face) in dereth_classic_dat::fonts::REQUESTS {
            let spec = FontSpec {
                height,
                width,
                weight,
                italic: false,
                face: face.into(),
            };
            assert_eq!(
                measured(&spec).map(str::len),
                Some(218),
                "{face} {height}-{width}"
            );
        }
        let other = FontSpec {
            height: 12,
            width: 0,
            weight: 400,
            italic: false,
            face: "Times New Roman".into(),
        };
        assert_eq!(measured(&other), None);
    }
}
