/// A play state kept at the version before the last bag could grow reads whole and nothing in its
/// pack moves or is lost: the pack's own items past its places, kept numbered from just past the
/// last bag, are still the pack's own after its other items, in their order, with a last bag of six
/// more places; every other item keeps its slot. What this build keeps of it reads the same.
/// Behaviour: server.operator.an-old-save-keeps-its-items-past-the-bags
#[test]
fn a_play_state_kept_at_version_twenty_seven_keeps_its_items_past_the_bags_in_the_pack() {
    use yalain_world::inventory::{self, OVERFLOW};
    let old = bytes(PLAY_27);
    assert_eq!(
        old[..4],
        27u32.to_le_bytes(),
        "the bytes are of that version"
    );
    let read = PlayState::from_bytes(&old).expect("reads");
    assert_eq!(read.left_kingdom, 1_700_000_000, "the rest as it was");
    assert_eq!(read.items.len(), 60, "none lost");
    // As that version read its own slots: the pack itself past 77, else 42, 54 and 66 begin the bags.
    let then = |slot: u32| match slot {
        0..42 | 78.. => 0,
        42..54 => 1,
        54..66 => 2,
        _ => 3,
    };
    let in_order = |items: &[Held], segment_of: &dyn Fn(u32) -> usize| {
        let mut pack: Vec<(usize, u32, u64)> = items
            .iter()
            .filter(|h| h.location == 0)
            .map(|h| (segment_of(h.slot), h.slot, h.id))
            .collect();
        pack.sort_unstable();
        pack.into_iter()
            .map(|(s, _, id)| (s, id))
            .collect::<Vec<_>>()
    };
    let was = {
        // The bytes' own items, as that version numbered them.
        let mut r = &old[16..];
        let n = u32::from_le_bytes(r[..4].try_into().expect("a count"));
        r = &r[4..];
        (0..n)
            .map(|i| {
                let at = 24 * i as usize;
                let w = |o: usize| u32::from_le_bytes(r[at + o..at + o + 4].try_into().expect("4"));
                Held {
                    id: u64::from_le_bytes(r[at..at + 8].try_into().expect("8")),
                    template: w(8),
                    slot: w(12),
                    location: w(16),
                    quantity: w(20),
                }
            })
            .collect::<Vec<_>>()
    };
    assert_eq!(
        in_order(&read.items, &inventory::segment_of),
        in_order(&was, &then),
        "each item in its segment, in its order"
    );
    for (now, kept) in read.items.iter().zip(&was) {
        assert_eq!(
            (now.id, now.template, now.quantity, now.location),
            (kept.id, kept.template, kept.quantity, kept.location)
        );
        if kept.location == 0 && kept.slot >= 78 {
            assert_eq!(
                now.slot,
                OVERFLOW + kept.slot - 78,
                "the pack's own, numbered on"
            );
        } else {
            assert_eq!(now.slot, kept.slot, "where it was");
        }
    }
    let grown = inventory::rooms(6);
    let mut items = read.items.clone();
    assert!(!inventory::fit_bags(&mut items, &grown), "nothing to move");
    assert_eq!(
        inventory::pack_segments(&items, &grown),
        [(42, 44), (12, 2), (12, 1), (18, 12)],
        "the two past the pack's places still its own"
    );
    let kept = read.to_bytes();
    assert_ne!(kept, old, "kept at this build's own version");
    assert_eq!(PlayState::from_bytes(&kept).expect("reads again"), read);
}

