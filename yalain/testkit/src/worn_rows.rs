//! The test world's worn looks, as the world's `[[worn]]` rows give them: 147 looks of 75 templates
//! whose data names none, each template's in its rows' order.

use yalain_content::worn_table::{Worn, WornLooks};

/// The test world's worn looks ([`TEST_WORN`]), once.
#[must_use]
pub fn test_worn_looks() -> &'static WornLooks {
    static LOOKS: std::sync::OnceLock<WornLooks> = std::sync::OnceLock::new();
    LOOKS.get_or_init(|| {
        WornLooks::of_rows(
            TEST_WORN
                .iter()
                .map(|&(template, races, sexes, appearance)| Worn {
                    template,
                    races,
                    sexes,
                    appearance,
                }),
        )
    })
}

