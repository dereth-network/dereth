/// A mouse button.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Button {
    Left,
    Right,
    Middle,
}

/// One event from the host.
#[derive(Clone, Debug, PartialEq)]
pub enum Event {
    /// A key went down (`repeat` when the keyboard repeats it while held) or up.
    Key { key: Key, down: bool, repeat: bool },
    /// Text typed.
    Text(String),
    /// What the input method is composing, not yet written; empty once it has written it or given
    /// up.
    Composing(String),
    /// A mouse button went down or up.
    Button { button: Button, down: bool },
    /// The pointer moved to a point of the window, in pixels from its top left.
    Pointer { x: f32, y: f32 },
    /// The mouse moved, in its own counts (x right, y toward the player), whatever the pointer
    /// does.
    Motion { dx: f32, dy: f32 },
    /// The wheel turned, in notches (positive away from the player).
    Wheel { notches: f32 },
    /// The window's drawing area changed size, in pixels.
    Resized { width: u32, height: u32 },
    /// The window gained or lost the keyboard.
    Focus(bool),
    /// The window was asked to close.
    Close,
}
