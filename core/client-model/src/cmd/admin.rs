#[cfg(test)]
mod tests {
    //! Behaviour: none (the table's own consistency; a server's test holds it to its commands).
    use super::*;

    #[test]
    fn no_command_is_listed_twice_and_each_says_what_it_does() {
        for (i, a) in ADMIN_COMMANDS.iter().enumerate() {
            assert!(!a.about.is_empty(), "{} says nothing", a.verb);
            assert!(
                !a.verb.contains(' '),
                "{} cannot be reached: the server splits a line on spaces",
                a.verb
            );
            assert!(
                ADMIN_COMMANDS[i + 1..]
                    .iter()
                    .all(|b| !b.verb.eq_ignore_ascii_case(a.verb)),
                "{} is listed twice",
                a.verb
            );
        }
    }

    #[test]
    fn every_command_reaches_the_server_as_it_is_typed() {
        use crate::cmd::{CommandInterp, CommandOutcome, TalkFocus};
        let mut interp = CommandInterp::new();
        for a in ADMIN_COMMANDS {
            let line = format!("@{}", a.verb);
            assert_eq!(
                interp.on_chat_command(&line, 1, TalkFocus::Say),
                CommandOutcome::ForwardVerbatim(line),
                "the client would answer it itself"
            );
        }
    }

    #[test]
    fn what_acts_on_the_selection_is_in_the_table() {
        for verb in ["delete", "smite", "forcelogout", "propertydump", "heal"] {
            assert!(admin_command(verb).is_some(), "{verb}");
            assert!(admin_uses_selection(verb), "{verb}");
        }
        assert!(!admin_needs_selection("heal"), "alone it heals the player");
        assert!(!admin_uses_selection("teleto"));
    }

    #[test]
    fn a_command_is_found_by_its_word_in_any_case() {
        assert_eq!(admin_command("TELETO").map(|c| c.verb), Some("teleto"));
        assert_eq!(admin_command("moveto").map(|c| c.verb), Some("MoveTo"));
        assert!(admin_command("no-such-command").is_none());
    }
}
