/// Decode one stored row and report how many bytes were left over. The client's `Pack` pads the
/// module to 4 after the collection, and ACE keeps the padding, so a row may end in up to three
/// zero bytes that are not part of the collection.
fn decode_row(parts: &[&str]) -> (PackObjPropertyCollection, Vec<u8>) {
    let bytes = hex(parts);
    let mut r = Reader::new(&bytes);
    let c = PackObjPropertyCollection::read(&mut r).expect("stored gameplay options decode");
    let tail = bytes[r.position()..].to_vec();
    assert!(
        tail.len() < 4,
        "{} bytes left over, which is more than align-to-4",
        tail.len()
    );
    assert!(
        tail.iter().all(|&b| b == 0),
        "the leftover bytes are not padding: {tail:02X?}"
    );

    // Re-encoding must reproduce the input exactly: nothing was dropped and no field was
    // normalised on the way in.
    let mut w = Writer::new();
    c.write(&mut w).expect("re-encode");
    assert_eq!(w.as_slice(), &bytes[..bytes.len() - tail.len()]);
    (c, tail)
}

/// The array every one of these bags consists of: one `Option_PlacementArray` property holding
/// `Option_Placement` structs, one per window, in window order.
fn placements(c: &PackObjPropertyCollection) -> Vec<Vec<(u32, BasePropertyValue)>> {
    assert_eq!(c.version, PackObjPropertyCollection::CORE_VERSION);
    assert_eq!(c.properties.entries.len(), 1);
    let (key, prop) = &c.properties.entries[0];
    assert_eq!(*key, OPTION_PLACEMENT_ARRAY);
    assert_eq!(prop.name, OPTION_PLACEMENT_ARRAY);
    let Some(BasePropertyValue::Array(items)) = &prop.value else {
        panic!("Option_PlacementArray is not an Array: {:?}", prop.value)
    };
    items
        .iter()
        .map(|p| {
            assert_eq!(p.name, OPTION_PLACEMENT);
            let Some(BasePropertyValue::Struct(t)) = &p.value else {
                panic!("Option_Placement is not a Struct")
            };
            t.entries
                .iter()
                .map(|(k, m)| {
                    assert_eq!(*k, m.name, "the hash key repeats the property name");
                    (m.name, m.value.clone().expect("a named member has a value"))
                })
                .collect()
        })
        .collect()
}

/// The whole point: each of the three rows is consumed to its exact end. A wrong value width for
/// any of the seven property names involved lands the cursor somewhere else in at least one of
/// them.
#[test]
fn all_three_stored_rows_are_consumed_exactly() {
    for (name, parts, len, pad) in [
        ("RowA", ROWA, 192, 0usize),
        ("RowB", ROWB, 132, 3),
        ("RowC", ROWC, 144, 0),
    ] {
        let bytes = hex(parts);
        assert_eq!(bytes.len(), len, "{name}");
        let (c, tail) = decode_row(parts);
        assert_eq!(tail.len(), pad, "{name}: unexpected padding");
        // All three are the same 17-window array; only the populated windows differ.
        assert_eq!(placements(&c).len(), 17, "{name}");
    }
}

/// The values themselves, which is what makes this a decode rather than a length check: two of the
/// three characters had resized the same windows, and one had hidden one.
#[test]
fn the_stored_rows_hold_the_placements_the_player_made() {
    use BasePropertyValue::{Bool, Integer};

    let (rowa, _) = decode_row(ROWA);
    let b = placements(&rowa);
    assert_eq!(
        b[5],
        [
            (OPTION_PLACEMENT_WIDTH, Integer(610)),
            (OPTION_PLACEMENT_HEIGHT, Integer(120))
        ]
    );
    assert_eq!(
        b[7],
        [
            (OPTION_PLACEMENT_X, Integer(0)),
            (OPTION_PLACEMENT_Y, Integer(500)),
            (OPTION_PLACEMENT_WIDTH, Integer(410)),
            (OPTION_PLACEMENT_HEIGHT, Integer(100)),
        ]
    );
    assert!(b
        .iter()
        .enumerate()
        .all(|(i, w)| [5, 7].contains(&i) || w.is_empty()));

    let (rowb, _) = decode_row(ROWB);
    let g = placements(&rowb);
    assert_eq!(g[12], [(OPTION_PLACEMENT_VISIBILITY, Bool(false))]);
    assert!(g.iter().enumerate().all(|(i, w)| i == 12 || w.is_empty()));

    let (rowc, _) = decode_row(ROWC);
    let n = placements(&rowc);
    assert_eq!(
        n[5],
        [
            (OPTION_PLACEMENT_WIDTH, Integer(610)),
            (OPTION_PLACEMENT_HEIGHT, Integer(120))
        ]
    );
    assert!(n.iter().enumerate().all(|(i, w)| i == 5 || w.is_empty()));
}

/// The live message. `read_body` asserts the body is consumed exactly, so this proves the two
/// `PackableList`s that follow the module still line up — which is what a wrong collection length
/// would break, silently and much later.
#[test]
fn the_live_player_description_decodes_and_re_encodes() {
    let body = hex(LIVE_PLAYER_DESCRIPTION);
    assert_eq!(body.len(), 2948);
    let d: LoginPlayerDescription = read_body(&body).expect("0x0013 decodes");

    let opts = d
        .player_module
        .gameplay_options
        .as_ref()
        .expect("the 0x0200 branch was taken");
    assert_eq!(placements(opts).len(), 17);

    // The wire section is RowC's stored row, byte for byte.
    let mut w = Writer::new();
    opts.write(&mut w).expect("re-encode");
    assert_eq!(w.as_slice(), &hex(ROWC)[..]);

    assert_eq!(
        dereth_protocol::write_body(&d).expect("re-encode the message"),
        body
    );
}
